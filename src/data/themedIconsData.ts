export function getThemedIcons(themeCategoryOrId?: string): ThemedIconItem[] {
  if (!themeCategoryOrId) return TURTLE_SANCTUARY_ICONS;
  const isTurtle = themeCategoryOrId === 'turtle' || themeCategoryOrId === 'theme-turtle';
  if (isTurtle) {
    return TURTLE_SANCTUARY_ICONS;
  }
  const isDino = themeCategoryOrId === 'dinosaur' || themeCategoryOrId === 'theme-dino';
  if (isDino) {
    return DINO_KINGDOM_ICONS;
  }
  const isFrog = themeCategoryOrId === 'frog' || themeCategoryOrId === 'theme-frog';
  if (isFrog) {
    return RIBBIT_POND_ICONS;
  }
  const isTrain = themeCategoryOrId === 'train' || themeCategoryOrId === 'theme-trains';
  if (isTrain) {
    return STEAM_EXPRESS_ICONS;
  }
  const isSpace = themeCategoryOrId === 'space' || themeCategoryOrId === 'theme-space';
  if (isSpace) {
    return COSMIC_SPACE_ICONS;
  }
  const isOcean = themeCategoryOrId === 'ocean' || themeCategoryOrId === 'theme-ocean';
  if (isOcean) {
    return OCEAN_SPLASH_ICONS;
  }
  const isFantasy = themeCategoryOrId === 'fantasy' || themeCategoryOrId === 'theme-fantasy' || themeCategoryOrId === 'magic';
  if (isFantasy) {
    return FAIRYTALE_MAGIC_ICONS;
  }
  const isRacing = themeCategoryOrId === 'racing' || themeCategoryOrId === 'theme-racing';
  if (isRacing) {
    return RACING_SPEEDWAY_ICONS;
  }
  return OTHER_THEMED_ICONS.filter(
    (item) => item.themeCategory === themeCategoryOrId || themeCategoryOrId.includes(item.themeCategory)
  );
}

